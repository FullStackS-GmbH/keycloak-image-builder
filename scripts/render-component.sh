#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
output=$(mktemp)
trap 'rm -f "$output"' EXIT
{
  printf '# Generated by scripts/render-component.sh. Edit ci/component.yml and Dockerfile.\n'
  cat ci/component.yml
  sed '/./s/^/        /' Dockerfile
} > "$output"
if [[ ${1:-} == --check ]]; then
  diff -u templates/build-keycloak/template.yml "$output"
else
  mkdir -p templates/build-keycloak
  cp "$output" templates/build-keycloak/template.yml
fi
