#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
image=$(sed -n 's/^ARG KEYCLOAK_IMAGE=//p' Dockerfile)
pattern='^quay\.io/keycloak/keycloak:26\.[0-9]+\.[0-9]+@sha256:[a-f0-9]{64}$'
[[ $image =~ $pattern ]] || {
  echo 'Pin an official Keycloak 26.x image with digest.' >&2
  exit 1
}
output=$(mktemp)
trap 'rm -f "$output"' EXIT
{
  printf '# Generated by scripts/render-component.sh. Edit ci/component.yml and Dockerfile.\n'
  sed "s|__KEYCLOAK_IMAGE__|$image|" ci/component.yml
  sed '/./s/^/        /' Dockerfile
} > "$output"
if [[ ${1:-} == --check ]]; then
  diff -u templates/build-keycloak/template.yml "$output"
else
  mkdir -p templates/build-keycloak
  cp "$output" templates/build-keycloak/template.yml
fi
